#!/usr/bin/env python3
"""Verify FINAL RUN production outputs against the submit files and summarise per sample.
For each expected (sample, seed) in scripts/condor/production_final_*.sub: Delphes .root, _gen.root and .json exist;
n_lhe == n_requested; n_delphes == n_lhe (fixed order) or > 0 (MLM, Pythia vetoes); Pythia sigma parsed.
sigma closure: fixed order -> mean Pythia sigma over jobs vs gridpack total (MG5 status file); MLM -> matched Pythia sigma.
Writes work/final_ntuples/verify.json and (with --ntuple) scripts/condor/ntuple_final_<tag>.sub for verified,
not-yet-ntupled files (chunks of 100 files; direct mode + ff modes where requested).
Usage: python3 -P verify_final.py [--ntuple TAG]"""
import sys, os, json, glob, re
P = "/eos/home-r/rjiang/vbs_zh_codex_starter"; PU = "/eos/user/r/rjiang/vbs_zh_codex_starter"
NT = f"{P}/work/final_ntuples"
FFMODES = {"F_QCD_llajj_vbs": ["ff1"], "F_EW_llajj_vbs": ["ff1"]}
exp = {}
for sub in sorted(glob.glob(f"{P}/scripts/condor/production_final_*.sub")):
    txt = open(sub).read(); body = txt.split("queue sample, gseed, cmnd, nev, seed, flav from (")[1]
    for l in body.strip().strip(")").splitlines():
        if l.strip():
            s, g, c, n, seed, f = l.split(); exp.setdefault(s, []).append((int(seed), int(n), int(g), c))
V = {}
for s, jobs in exp.items():
    D = f"{P}/production/final/{s}"; ok, bad, missing = [], [], []
    mlm = "mlm" in jobs[0][3]
    for seed, n, g, c in jobs:
        t = f"{D}/{s}_s{seed}"
        if not os.path.exists(t + ".root"): missing.append(seed); continue
        try:
            j = json.load(open(t + ".json")); assert os.path.getsize(t + "_gen.root") > 0
            sig = float(j["pythia_sum_line"].split("|")[-2].split()[0])*1e12   # mb -> fb
            good = j["n_lhe"] == n and (j["n_delphes"] > 0 if mlm else j["n_delphes"] == j["n_lhe"])
            (ok if good else bad).append(dict(seed=seed, n_lhe=j["n_lhe"], n_del=j["n_delphes"], sig=sig))
        except Exception as e:
            bad.append(dict(seed=seed, err=str(e)))
    nd = sum(o["n_del"] for o in ok); nl = sum(o["n_lhe"] for o in ok)
    sig_py = (sum(o["sig"]*o["n_lhe"] for o in ok)/nl) if nl else None
    st = f"{P}/production/gridpacks/{s}_status.txt"; sig_gp = None
    if os.path.exists(st):
        m = re.search(r"Cross-section :\s*([0-9.eE+-]+)\s*\+-\s*([0-9.eE+-]+)", open(st).read())
        if m: sig_gp = (float(m.group(1))*1e3, float(m.group(2))*1e3)
    V[s] = dict(expected=len(jobs), ok=len(ok), bad=bad, missing=missing, mlm=mlm, n_lhe=nl, n_delphes=nd,
                sigma_pythia_fb=sig_py, sigma_gridpack_fb=sig_gp,
                closure=(sig_py/sig_gp[0] - 1) if (sig_py and sig_gp and not mlm) else None,
                sigma_used_fb=(sig_py if mlm else (sig_gp[0] if sig_gp else sig_py)),
                files=[f"{PU}/production/final/{s}/{s}_s{o['seed']}.root" for o in ok])
    print(f"{s:22s} ok {len(ok):4d}/{len(jobs):4d} bad {len(bad):3d} missing {len(missing):4d} N_del {nd:8d} "
          f"sig_py {sig_py if sig_py is None else round(sig_py, 5)} sig_gp {sig_gp} closure {V[s]['closure']}")
json.dump({k: {kk: vv for kk, vv in v.items() if kk != 'files'} for k, v in V.items()}, open(f"{NT}/verify.json", "w"), indent=1)
if "--ntuple" in sys.argv:
    tag = sys.argv[sys.argv.index("--ntuple") + 1]; L = []
    for s, v in V.items():
        if v["ok"] != v["expected"]: continue        # ntuple only complete samples (avoids partial duplicates)
        F = v["files"]
        for k in range(0, len(F), 100):
            for mode in ["direct"] + FFMODES.get(s, []):
                name = f"{s}__c{k//100:03d}" + ("" if mode == "direct" else "_" + mode)
                if not os.path.exists(f"{NT}/{name}.npz"): L.append(f"  {name} {mode} {','.join(F[k:k+100])}")
    hdr = f"""# FINAL RUN ntupling (generated by scripts/analysis/verify_final.py --ntuple {tag})
universe = vanilla
executable = {PU}/scripts/analysis/ntuple_job.sh
arguments = $(name) $(mode) $(files)
should_transfer_files = YES
transfer_output_files = ""
output = {PU}/production/condor_logs/final/ntuple_$(name).out
error  = {PU}/production/condor_logs/final/ntuple_$(name).err
log    = {PU}/production/condor_logs/ntuple_final.log
request_cpus = 1
request_memory = 4000
+JobFlavour = "longlunch"
max_retries = 2
queue name, mode, files from (
"""
    if L: open(f"{P}/scripts/condor/ntuple_final_{tag}.sub", "w").write(hdr + "\n".join(L) + "\n)\n")
    print(f"ntuple jobs written: {len(L)} -> scripts/condor/ntuple_final_{tag}.sub")
