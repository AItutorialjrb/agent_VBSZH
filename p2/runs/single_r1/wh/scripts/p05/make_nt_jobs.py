#!/usr/bin/env python3
"""single_r1 WH Phase 05: write the HTCondor job list for ntuple_wh.py over the frozen wh-prod-v1(.1) package (read-only),
the frozen ZH rows used as WH backgrounds (read-only) and own samples under runs/single_r1.
Output: wh/work/nt/<sample>/<sample>__cNNN.npz ; job list wh/scripts/condor/p05_nt.list ; submit file p05_nt.sub
Usage: python3 -P make_nt_jobs.py [sample ...]   (default: all)"""
import os, sys, glob
E = "/eos/user/r/rjiang/vbs_zh_codex_starter"; WP = f"{E}/p2/production/wh"; ZH = f"{E}/production"
WH = f"{E}/p2/runs/single_r1/wh"; NT = f"{WH}/work/nt"
MODES = {"F_EW_Wajj_nomjj": "D,F1", "F_QCD_Wajjj_nomjj": "D,F1", "T_tta_1l": "D,F1", "T_tWa_1l": "D,F1",
         "F_Wjjjj": "D,F2", "T_ttjj_1l": "D,F2",
         "Q_aajj": "D,FL", "Q_aajjj": "D,FL", "H_VBFH_jj": "D,FL", "H_ggF_jj_nomjj": "D,FL",
         "F_QCD_llajj_loose": "D,EG", "ZH_F_EW_llajj_vbs": "D,EG", "V_WWa_WH": "D,EG", "V_WZa_WH": "D,EG", "V_ZZa_WH": "D,EG"}
# frozen ZH directories (one sample key per directory; normalisation per directory, FORMAT v1.1 notes)
ZHDIR = {"ZH_B_QCD_zaajj_nomjj": f"{ZH}/final/B_QCD_zaajj_nomjj", "ZH_B_QCD_zaajj_vbs": f"{ZH}/final/B_QCD_zaajj_vbs",
         "ZH_B_EW_zaajj_vbs_is1h": f"{ZH}/final/B_EW_zaajj_vbs_is1h", "ZH_B_EW_zaajj_vbs_is2": f"{ZH}/final/B_EW_zaajj_vbs_is2",
         "ZH_B_EW_zaajj_vbs_is3": f"{ZH}/final/B_EW_zaajj_vbs_is3", "ZH_F_EW_llajj_vbs": f"{ZH}/final/F_EW_llajj_vbs",
         "ZH_ew_zhjj_zll": f"{ZH}/v1/ew_zhjj_zll", "ZH_qcd_zhjj_zll": f"{ZH}/v1/qcd_zhjj_zll"}
OWN = {"H_ggF_jj_nomjj": f"{WH}/work/prod/H_ggF_jj_nomjj"}
def files(d): return sorted(f for f in glob.glob(f"{d}/*.root") if not f.endswith(("_gen.root", "_full.root")))
want = set(sys.argv[1:])
src = {s: f"{WP}/{s}" for s in sorted(os.listdir(WP)) if os.path.isdir(f"{WP}/{s}")}
src.update(ZHDIR); src.update(OWN)
lines = []
for s, d in src.items():
    if want and s not in want: continue
    F = files(d)
    if not F: print("no files:", s); continue
    nper = max(1, min(25, int(2.0e5 // max(1, os.path.getsize(F[0])//400))))  # ~ equal work per job (file size proxy)
    os.makedirs(f"{NT}/{s}", exist_ok=True)
    for i in range(0, len(F), nper):
        out = f"{NT}/{s}/{s}__c{i//nper:03d}.npz"
        if os.path.exists(out): continue
        lines.append(f"{out} {MODES.get(s, 'D')} {90000 + len(lines)} {','.join(F[i:i+nper])}")
lst = f"{WH}/scripts/condor/p05_nt{'_' + '_'.join(sorted(want)) if want else ''}.list"
open(lst, "w").write("\n".join(lines) + "\n")
open(f"{WH}/scripts/condor/p05_nt_job.sh", "w").write(f"""#!/bin/bash
# single_r1 WH Phase 05 ntuple job (reads EOS via fuse, writes the .npz to EOS); args: <list file> <0-based line>
# (condor "queue ... from" splits on commas, so the job reads its own line: out modes seed comma-files)
read OUT MODES SEED F <<< "$(sed -n "$(( $2 + 1 ))p" "$1")"; FILES=$(echo $F | tr ',' ' ')
export PROJECT={E}/p2/lib; source {E}/p2/lib/scripts/setup_stack.sh >/dev/null 2>&1 || exit 11
[ -f "$OUT" ] && {{ echo exists; exit 0; }}
python3 -P {WH}/scripts/p05/ntuple_wh.py /tmp/nt_$$.npz $MODES $SEED $FILES || exit 12
cp /tmp/nt_$$.npz "$OUT.tmp" && mv "$OUT.tmp" "$OUT" || exit 13
rm -f /tmp/nt_$$.npz
""")
os.chmod(f"{WH}/scripts/condor/p05_nt_job.sh", 0o755)
open(lst.replace(".list", ".sub"), "w").write(f"""# GENERATED by wh/scripts/p05/make_nt_jobs.py (single_r1) — Phase 05 ntuples (no generation)
# Submit: bash -lc 'module load lxbatch/eossubmit; cd {WH}/scripts/condor; condor_submit {os.path.basename(lst).replace('.list', '.sub')}'
universe   = vanilla
executable = {WH}/scripts/condor/p05_nt_job.sh
arguments  = {lst} $(Process)
output     = {WH}/work/condor/nt2/nt_$(Cluster)_$(Process).out
error      = {WH}/work/condor/nt2/nt_$(Cluster)_$(Process).err
log        = {WH}/work/condor/nt2/nt.log
request_cpus = 1
request_memory = 4000
+JobFlavour = "microcentury"
max_retries = 2
queue {len(lines)}
""")
print(f"{len(lines)} jobs -> {lst}")
