#!/usr/bin/env python3
"""single_r1 WH Phase 03: write HTCondor submit files (EosSubmit schedd) from the registry in make_cards.py.
  wh/scripts/condor/p03_gridpacks.sub : one gridpack build per gridpack card (cluster _b onward: wh/scripts/condor/make_gridpack.sh = lib + patch 002)
  wh/scripts/condor/p03_xsec.sub      : sigma-only validation runs for the *_nodec cards (lib mg5_run.sh, unmodified)
  wh/scripts/condor/p03_test.sub      : one 2000-event test job per sample type (lib run_job.sh, unmodified):
                                        gridpack -> PY8 (CP5) -> Delphes slim_v1 -> GenTruth; holds until gridpack exists.
Seeds: gridpack/xsec J=0, test job J=1 (SPEC_G0 §3.4); uniqueness asserted here and in make_cards.py.
Usage: python3 -P wh/scripts/make_submit.py   (then submit by hand: see header of each .sub)
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_cards as MC

E = "/eos/user/r/rjiang/vbs_zh_codex_starter"; LIB = f"{E}/p2/lib"; WH = f"{E}/p2/runs/single_r1/wh"
GP, LOG = f"{WH}/work/gridpacks", f"{WH}/work/condor"
# (ncore, mem MB, flavour) for gridpack builds; heavy multi-boson+photon processes get more cores / longer flavour
RES = {"B_EW_wpaajj": (16, 32000, "tomorrow"), "B_EW_wmaajj": (16, 32000, "tomorrow"),
       "B_QCD_lvaajj": (16, 32000, "tomorrow"), "B_QCD_lvaajj_nomjj": (16, 32000, "tomorrow"),
       "F_QCD_lvajj": (8, 16000, "tomorrow"), "F_EW_lvajj": (8, 16000, "tomorrow"), "F_Wjj": (8, 16000, "workday"),
       "T_ttaa_1l": (8, 16000, "workday"), "S_EW_WHjj_offshell": (8, 16000, "workday"), "B_QCD_aajj": (16, 32000, "tomorrow"), "H_ggF_Hjj": (8, 16000, "workday")}
DEF = (4, 8000, "workday")

def head(desc, exe, args, tif, logname, flav="$(flav)", cpus="$(ncore)", mem="$(mem)"):
    return f"""# GENERATED by wh/scripts/make_submit.py (single_r1) — {desc}
# Submit:  bash -lc 'module load lxbatch/eossubmit; cd {WH}/scripts/condor; condor_submit <this file>'
universe     = vanilla
should_transfer_files   = YES
when_to_transfer_output = ON_EXIT
executable   = {exe}
arguments    = {args}
transfer_input_files = {tif}
output       = {LOG}/{logname}_$(name).out
error        = {LOG}/{logname}_$(name).err
log          = {LOG}/{logname}.log
request_cpus   = {cpus}
request_memory = {mem}
request_disk   = 20000000
+JobFlavour  = "{flav}"
"""

def main():
    imin = int(sys.argv[1]) if len(sys.argv) > 1 else 0; suf = sys.argv[2] if len(sys.argv) > 2 else ""
    os.makedirs(f"{WH}/scripts/condor", exist_ok=True)
    gpc = [s for s in MC.S if s["gridpack"] and s["idx"] >= imin]; xsc = [s for s in MC.S if not s["gridpack"] and s["idx"] >= imin]
    seeds = [s["seed_gp"] for s in MC.S] + [s["seed_gp"] + 1 for s in MC.S if s["gridpack"]]
    assert len(seeds) == len(set(seeds)), "seed collision"
    # gridpacks
    t = head("gridpack builds", f"{WH}/scripts/condor/make_gridpack.sh", f"$(name) $(gseed) {GP} $(ncore)",
             f"{LIB}/scripts/setup_stack.sh, {WH}/cards/$(name).mg5" + (f", {WH}/cards/heft.tgz" if any(s["model"].startswith("heft") for s in gpc) else ""), "gp")
    t += "max_retries  = 1\nqueue name, gseed, ncore, mem, flav from (\n"
    for s in gpc:
        n, m, f = RES.get(s["name"], DEF); t += f"  {s['name']} {s['seed_gp']} {n} {m} {f}\n"
    open(f"{WH}/scripts/condor/p03_gridpacks{suf}.sub", "w").write(t + ")\n")
    # sigma-only validation runs
    t = head("sigma-only validation runs (LHE kept)", f"{LIB}/scripts/condor/mg5_run.sh", f"$(name) $(gseed) {WH}/work/xsec $(ncore)",
             f"{LIB}/scripts/setup_stack.sh, {WH}/cards/$(name).mg5", "xs")
    t += "max_retries  = 1\nqueue name, gseed, ncore, mem, flav from (\n"
    for s in xsc:
        t += f"  {s['name']} {s['seed_gp']} 4 8000 workday\n"
    open(f"{WH}/scripts/condor/p03_xsec{suf}.sub", "w").write(t + ")\n")
    # test jobs
    tif = ", ".join([f"{LIB}/scripts/setup_stack.sh", f"{LIB}/scripts/run_py8_delphes.sh", f"{LIB}/scripts/slim_gentruth.py",
                     f"{LIB}/cards/phase03_smoke/py8_common_CP5.cmnd", f"{WH}/cards/$(cmnd)",
                     f"{LIB}/cards/phase04_candidates/delphes_card_CMS_slim_v1.tcl"])
    t = head("one test job per sample type (2000 ev)", f"{LIB}/scripts/condor/run_job.sh",
             f"$(name) {GP}/$(name)_gridpack_s$(gseed).tar.gz $(nev) $(seed) $(cmnd) {WH}/work/test/$(name) $(klhe) $(kfull)",
             tif, "test", cpus=1, mem=3000)
    t += """max_retries  = 2
on_exit_hold = (ExitCode =?= 19)
on_exit_hold_reason = "gridpack not yet available"
periodic_release = (HoldReasonCode =?= 3) && ((time() - EnteredCurrentStatus) > 1800) && (NumJobStarts < 200)
queue name, gseed, seed, cmnd, nev, klhe, kfull, flav from (
"""
    for s in gpc:
        full = 1 if s["role"] in ("signal", "resonant_bkg") else 0
        t += f"  {s['name']} {s['seed_gp']} {s['seed_gp'] + 1} {s['py8']} 2000 1 {full} longlunch\n"
    open(f"{WH}/scripts/condor/p03_test{suf}.sub", "w").write(t + ")\n")
    print(f"gridpacks {len(gpc)}, xsec {len(xsc)}, test {len(gpc)}; seeds unique ({len(seeds)})")

if __name__ == "__main__":
    main()
