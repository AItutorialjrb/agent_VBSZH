def run_lines(s):
    r = {**COMMON_RUN, **s["run"], "gridpack": "True" if s["gridpack"] else "False", "nevents": s["nevents"], "iseed": "SEED"}
    return "\n".join(f"set run_card {k} {v}" for k, v in r.items())

def main():
    os.makedirs(f"{WH}/cards", exist_ok=True); os.makedirs(f"{WH}/config", exist_ok=True)
    seeds = [s["seed_gp"] for s in S]; names = [s["name"] for s in S]; idxs = [s["idx"] for s in S]
    assert len(set(seeds)) == len(seeds) and len(set(names)) == len(names) and len(set(idxs)) == len(idxs), "duplicate seed/name/idx"
    for s in S:
        for f in s["br"]:
            assert f in BRF and s["br"].count(f) == 1, (s["name"], f)
        assert not ("WF" in s["br"] and "WF_tau" in s["br"])
        body = HEADER.format(name=s["name"], note=s["note"], model=s["model"]) + "\n".join(s["procs"]) + \
            "\noutput OUTDIR -nojpeg\nlaunch OUTDIR\n0\n" + run_lines(s) + "\ndone\n"
        open(f"{WH}/cards/{s['name']}.mg5", "w").write(body)
    with open(f"{WH}/config/samples.yaml", "w") as y:
        y.write("# GENERATED by wh/scripts/make_cards.py (single_r1). Do not edit by hand.\n")
        y.write(f"br_factors: {json.dumps(BRF)}\nseed_scheme: 'seed = 2000000 + 400000 + 1000*idx + J'\nsamples:\n")
        for s in S:
            y.write(f"  - {json.dumps({k: s[k] for k in ('idx','name','role','br','py8','mode','seed_gp','note')})}\n")
    print(f"wrote {len(S)} cards; seeds unique; BR factors at most once per sample")

if __name__ == "__main__":
    main()
