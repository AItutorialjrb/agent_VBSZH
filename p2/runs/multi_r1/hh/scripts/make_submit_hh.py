#!/usr/bin/env python3
"""Generate HTCondor submit files (EosSubmit schedd) for the hh Phase-03 gridpack builds and test jobs from config/sample_matrix_gen.yaml.
Submit: bash -lc 'module load lxbatch/eossubmit; cd <hh>/scripts/condor; condor_submit <file>'   (check condor_q for duplicates FIRST).
Usage: python3 -P make_submit_hh.py"""
import yaml, os, sys
PREF = sys.argv[1] if len(sys.argv) > 1 else ""      # optional sample-name prefix filter (gridpack file only)
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
E = H.replace("/eos/home-r/", "/eos/user/r/")          # same files, schedd-visible path
L = "/eos/user/r/rjiang/vbs_zh_codex_starter/p2/lib"
m = yaml.safe_load(open(f"{H}/config/sample_matrix_gen.yaml"))
res = {"Q_4j_vbs": (8, 16000, "testmatch"), "Q_bbjj_vbs": (4, 12000, "workday"), "G_ggHH_loop_kl1": (4, 8000, "workday")}
base = ["universe = vanilla", "should_transfer_files = YES", "when_to_transfer_output = ON_EXIT"]
# ---------------- gridpacks
o = ["# GENERATED by scripts/make_submit_hh.py - do not edit by hand (gridpacks)"] + base
o += [f"executable = {E}/scripts/condor/make_gridpack_hh.sh",
      f"arguments = $(card) $(gseed) {E}/work/gridpacks $(ncore) $(pcut)",
      f"transfer_input_files = {L}/scripts/setup_stack.sh, {E}/cards/$(card).mg5, {E}/scripts/patch_cuts_vbs.py, {E}/work/models/UFO_sm_kVk2VkL.tgz, {E}/work/models/UFO_loop_sm_kl.tgz",
      f"output = {E}/work/condor/gp_$(card).out", f"error = {E}/work/condor/gp_$(card).err", f"log = {E}/work/condor/gridpacks.log",
      "request_cpus = $(ncore)", "request_memory = $(mem)", "request_disk = 20000000", '+JobFlavour = "$(flav)"', "max_retries = 1",
      "queue card, gseed, ncore, mem, flav, pcut from ("]
for s in m["samples"]:
    if not s["phase03_gridpack"] or not s["name"].startswith(PREF): continue
    nc, mem, fl = res.get(s["name"], (4, 8000, "workday"))
    o.append(f"  {s['name']} {s['seed_gridpack']} {nc} {mem} {fl} {int(s['vbs_anypair_patch'])}")
o.append(")")
open(f"{H}/scripts/condor/gridpacks_hh{'_'+PREF if PREF else ''}.sub", "w").write("\n".join(o) + "\n")
if PREF: print("written filtered gridpack file for prefix", PREF); sys.exit(0)
# ---------------- test jobs (one per sample type; run_job_hh.sh)
o = ["# GENERATED by scripts/make_submit_hh.py - do not edit by hand (test jobs: one per sample type)"] + base
o += [f"executable = {E}/scripts/condor/run_job_hh.sh",
      f"arguments = $(sample) $(gpdir)/$(sample)_gridpack_s$(gseed).tar.gz $(nev) $INT(seed) $(cmnd) {E}/work/test/$(sample) 1 1",
      f"transfer_input_files = {L}/scripts/setup_stack.sh, {L}/scripts/run_py8_delphes.sh, {E}/scripts/slim_hh_truth.py, {L}/cards/phase03_smoke/py8_common_CP5.cmnd, {E}/cards/py8/$(cmnd), {E}/cards/delphes/delphes_card_CMS_slim_hh_v1.tcl",
      f"output = {E}/work/condor/test_$(sample).out", f"error = {E}/work/condor/test_$(sample).err", f"log = {E}/work/condor/test.log",
      "request_cpus = 1", "request_memory = 4000", '+JobFlavour = "$(flav)"', "max_retries = 1", "success_exit_code = 0",
      "on_exit_hold = (ExitCode =?= 19)", 'on_exit_hold_reason = "gridpack not yet available"',
      "periodic_release = (HoldReasonCode =?= 3) && ((time() - EnteredCurrentStatus) > 1800) && (NumJobStarts < 20)",
      "queue sample, gseed, cmnd, nev, seed, flav, gpdir from ("]
for s in m["samples"]:
    if s["phase03_test_job"]:
        o.append(f"  {s['name']} {s['seed_gridpack']} {s['pythia_cmnd']} 2000 {s['seed_test']} longlunch {E}/work/{'gridpacks_v2' if s['cls'] in ('signal','ggF_HH','validation') else 'gridpacks'}")
o.append(")")
open(f"{H}/scripts/condor/test_hh.sub", "w").write("\n".join(o) + "\n")
print("written gridpacks_hh.sub, test_hh.sub")
